"""Exercise voluntary onboarding, historical scope, resuming and mobile use."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
BASE=os.environ.get('ATLAS_BASE_URL','http://127.0.0.1:8000/')
errors=[]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    context=browser.new_context(viewport={'width':1440,'height':960},reduced_motion='reduce')
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE)
    page.wait_for_function('window.AtlasExperience && window.atlas')
    assert not page.locator('dialog[open]').count()
    assert not page.locator('#journey-coach').count()
    assert not page.locator('#map-options').get_attribute('open')
    assert page.locator('.book-circle').count()==73
    assert page.evaluate("(()=>{const ids=[...document.querySelectorAll('[id]')].map(e=>e.id);return new Set(ids).size===ids.length})()")
    page.screenshot(path=str(ROOT/'docs/experiencia-inicio.png'),full_page=True,animations='disabled')
    page.locator('#guide-button').focus()
    page.keyboard.press('Enter')
    assert page.locator('#guide-dialog').is_visible()
    page.keyboard.press('Escape')
    assert page.evaluate("document.activeElement.id==='guide-button'")
    # Starting and pausing must restore the exact prior view, including filters.
    page.evaluate("atlas.navigate({scenario:'scenario_alternatives',search:'Romanos',testament:'NT',labels:false,mode:'overview',selection:{type:'book',id:'book_rom'}})")
    before=page.evaluate('JSON.stringify(atlas.state)')
    page.click('#education-button')
    page.click('#first-thread')
    assert page.evaluate("atlas.state.selection.id==='book_sir'")
    assert page.locator('#journey-coach').is_visible()
    assert page.evaluate("(()=>{const r=document.querySelector('.overview-node[data-work=book_sir] .book-circle').getBoundingClientRect(),d=document.querySelector('#detail-panel').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.left>=0&&r.right<d.left})()")
    # Selecting the actual stage also advances the contextual lesson.
    page.locator('#detail-panel [data-stage="stage_sir_he"]').click()
    assert 'Las fechas tienen margen' in page.locator('#journey-coach').inner_text()
    page.click('#journey-pause')
    assert page.evaluate('JSON.stringify(atlas.state)')==before
    assert page.locator('#first-thread').inner_text().startswith('Retomar')
    page.select_option('#language','en')
    page.wait_for_function("AtlasI18n.getLanguage()==='en'")
    page.reload()
    page.wait_for_function('window.AtlasExperience')
    assert not page.locator('#journey-coach').count()
    assert not page.locator('dialog[open]').count()
    assert 'Resume my thread' in page.locator('#first-thread').inner_text()
    resumed_view=page.evaluate('JSON.stringify(atlas.state)')
    page.click('#education-button')
    page.click('#first-thread')
    assert 'Dates have margins' in page.locator('#journey-coach').inner_text()
    assert page.evaluate("atlas.state.selection.id==='stage_sir_he'")
    page.evaluate("atlas.select('book','book_gen')")
    assert 'Follow your curiosity.' in page.locator('#journey-coach').inner_text()
    assert page.evaluate("atlas.state.selection.id==='book_gen'")
    page.click('#journey-context')
    assert page.evaluate("atlas.state.selection.id==='stage_sir_he'")
    page.click('#journey-next')
    assert page.evaluate("atlas.state.mode==='stages'")
    assert page.locator('.graph-node').count()==2
    page.screenshot(path=str(ROOT/'docs/experiencia-etapas-en.png'),animations='disabled')
    page.click('#journey-next')
    assert page.evaluate("atlas.state.selection.id==='access_sir_he_gr_alt'")
    page.locator('[data-answer="1"]').click()
    assert page.locator('#journey-feedback').inner_text()
    assert page.evaluate("AtlasExperience.getProgress().completed.length===0")
    page.locator('[data-answer="0"]').click()
    assert page.evaluate("AtlasExperience.getProgress().completed.includes('translation')")
    page.click('#journey-free')
    assert page.evaluate('JSON.stringify(atlas.state)')==resumed_view
    page.evaluate("atlas.navigate({mode:'overview',scenario:'scenario_critical',selection:null,search:'',testament:'all',tour:'all',foundation:'all',neighborhood:false,pending:false,labels:true,zoom:1})")
    assert page.locator('.book-circle').count()==73
    assert '1 of 3 threads explored' in page.locator('#thread-status').inner_text()
    assert 'Explored' in page.locator('#thread-translation').inner_text()
    # Access without quotation must not turn into a claim of literary reuse.
    page.click('#education-button')
    page.locator('#thread-memory').click()
    page.click('#journey-next')
    assert page.evaluate("atlas.state.selection.id==='access_prior_1th_1co'")
    assert 'Shared Pauline authorship' in page.locator('#journey-coach').inner_text()
    assert 'Actual use not assessed' in page.locator('#detail-panel').inner_text()
    page.screenshot(path=str(ROOT/'docs/experiencia-acceso-en.png'),animations='disabled')
    page.click('#journey-next')
    page.locator('[data-answer="0"]').click()
    assert not page.evaluate("AtlasExperience.getProgress().completed.includes('memory')")
    page.locator('[data-answer="1"]').click()
    page.click('#journey-another')
    assert page.evaluate("document.activeElement.id==='thread-translation'")
    page.keyboard.press('Escape')
    page.select_option('#language','es')
    page.wait_for_function("AtlasI18n.getLanguage()==='es'")
    page.click('#education-button')
    page.click('#thread-uncertainty')
    page.click('#journey-next')
    assert page.evaluate("atlas.state.selection.id==='candidate_mark_matt'")
    page.click('#journey-next')
    assert page.evaluate("atlas.state.selection.id==='candidate_matt_luke' && atlas.state.pending")
    assert 'Candidatura pendiente' in page.locator('#detail-panel').inner_text()
    assert page.locator('.overview-connection[data-evaluation="candidate_matt_luke"] .overview-path').get_attribute('marker-end')==''
    page.click('#journey-next')
    assert page.evaluate("atlas.state.scenario==='scenario_alternatives' && atlas.state.selection.id==='candidate_matt_luke_alt'")
    assert 'Farrer' in page.locator('#detail-panel').inner_text()
    page.screenshot(path=str(ROOT/'docs/experiencia-incertidumbre.png'),animations='disabled')
    page.locator('[data-answer="1"]').click()
    page.click('#journey-free')
    assert page.evaluate("atlas.state.scenario==='scenario_critical' && !atlas.state.pending")
    assert '3 de 3 hilos explorados' in page.locator('#thread-status').inner_text()
    # Closed drawer keeps an explicit route back to a voluntary guide.
    page.click('#education-button')
    page.click('#first-thread')
    page.click('#detail-dismiss')
    assert page.locator('#thread-return').is_visible()
    page.click('#resume-open')
    assert page.locator('#journey-coach').is_visible()
    page.click('#journey-pause')
    for width in [320,390,768]:
        page.set_viewport_size({'width':width,'height':844})
        page.evaluate("window.scrollTo(0,0)")
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),width
        page.click('#education-button')
        page.click('#first-thread')
        assert page.locator('#journey-coach').is_visible()
        box=page.locator('#journey-coach').bounding_box()
        assert box['x']>=0 and box['x']+box['width']<=width
        page.click('#journey-next')
        page.click('#journey-next')
        assert page.locator('#journey-coach').is_visible()
        assert page.evaluate("getComputedStyle(document.querySelector('.thread-primary')).transitionDuration==='0s'")
        if width==390:page.screenshot(path=str(ROOT/'docs/experiencia-movil.png'),animations='disabled')
        page.click('#journey-map-back')
        assert page.locator('#thread-return').is_visible()
        page.click('#resume-open')
        page.click('#journey-pause')
    context.close()
    # Browsers denying storage must still complete the journey in memory.
    private=browser.new_context(viewport={'width':390,'height':844})
    private.add_init_script("Object.defineProperty(window,'localStorage',{get(){throw new DOMException('Storage blocked','SecurityError')}})")
    page=private.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(BASE)
    page.wait_for_function('window.AtlasExperience')
    page.click('#education-button')
    page.click('#first-thread')
    for _ in range(3):page.click('#journey-next')
    page.locator('[data-answer="0"]').click()
    assert page.evaluate('AtlasExperience.getProgress().completed.length===1')
    page.click('#journey-free')
    private.close()
    assert not errors,errors
    browser.close()
report={'passed':True,'browser_errors':errors,'flows':['voluntary onboarding without automatic popup','keyboard guide and focus return','direct stage selection advances lesson','exact view restoration on pause','progress resumes after reload without forced opening','ES/EN guided copy','scoped translation question with corrective feedback','same-author access remains distinct from actual use','pending connection keeps no arrowhead','scenario-specific assessment identifiers','completion persistence and replay','closed-drawer guide recovery','320/390/768 px layouts','reduced motion','storage-denied fallback']}
(ROOT/'qa/experience-results.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print('Recorridos, idiomas, memoria local y móvil comprobados sin errores.')
